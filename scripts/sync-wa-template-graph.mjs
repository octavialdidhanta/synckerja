/**
 * Inline canonical waTemplateGraph.ts into edge function index.ts for Supabase deploy.
 * Dashboard / some deploy paths only bundle index.ts — local ./waTemplateGraph.ts is not uploaded.
 *
 * Edit: supabase/functions/_shared/waTemplateGraph.ts
 * Run:  node scripts/sync-wa-template-graph.mjs
 */
import { readFileSync, writeFileSync, unlinkSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const canonicalPath = join(root, "supabase/functions/_shared/waTemplateGraph.ts");

const START = "// __INLINE_WA_TEMPLATE_GRAPH__";
const END = "// __INLINE_WA_TEMPLATE_GRAPH_END__";

const targets = [
  {
    indexPath: join(root, "supabase/functions/whatsapp-campaign-worker/index.ts"),
    sidecarPath: join(root, "supabase/functions/whatsapp-campaign-worker/waTemplateGraph.ts"),
  },
  {
    indexPath: join(root, "supabase/functions/send-whatsapp-template-followup/index.ts"),
    sidecarPath: join(root, "supabase/functions/send-whatsapp-template-followup/waTemplateGraph.ts"),
  },
];

function canonicalBody() {
  let text = readFileSync(canonicalPath, "utf8");
  // Drop canonical-only file header (keep exports).
  text = text.replace(
    /^\/\*\*[\s\S]*?After editing this file[\s\S]*?\*\/\s*/,
    "",
  );
  text = text.replace(
    /^\/\*\*[\s\S]*?Shared Meta WhatsApp[\s\S]*?\*\/\s*/,
    "",
  );
  return text.trim() + "\n";
}

function inlineIntoIndex(indexPath, body) {
  let index = readFileSync(indexPath, "utf8");
  const block = `${START}\n// Generated by scripts/sync-wa-template-graph.mjs — do not edit by hand.\n${body}${END}\n`;

  const betweenMarkers = new RegExp(
    `${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\n?`,
  );
  if (betweenMarkers.test(index)) {
    index = index.replace(betweenMarkers, block);
  } else {
    const importRe = /import\s*\{[^}]+\}\s*from\s*["']\.\/waTemplateGraph\.ts["'];\s*\n/;
    if (!importRe.test(index)) {
      throw new Error(`No waTemplateGraph import or markers in ${indexPath}`);
    }
    index = index.replace(importRe, `${block}\n`);
  }
  writeFileSync(indexPath, index, "utf8");
}

const body = canonicalBody();
for (const { indexPath, sidecarPath } of targets) {
  inlineIntoIndex(indexPath, body);
  if (existsSync(sidecarPath)) {
    unlinkSync(sidecarPath);
  }
  console.log(`inlined -> ${indexPath.replace(root + "\\", "").replace(root + "/", "")}`);
}
